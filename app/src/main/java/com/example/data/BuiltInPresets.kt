    private fun createPreset(
        id: String,
        name: String,
        category: String,
        exposure: Float = 0f,
        contrast: Float = 0f,
        highlights: Float = 0f,
        shadows: Float = 0f,
        whites: Float = 0f,
        blacks: Float = 0f,
        temperature: Float = 0f,
        tint: Float = 0f,
        vibrance: Float = 0f,
        saturation: Float = 0f,
        clarity: Float = 0f,
        dehaze: Float = 0f,
        vignette: Float = 0f,
        grain: Float = 0f,
        shadowHue: Float = 0f,
        shadowSat: Float = 0f,
        highlightHue: Float = 0f,
        highlightSat: Float = 0f,
        balance: Float = 0f,
        toneCurve: List<Pair<Float, Float>> = emptyList()
    ): XmpPreset {
        val preset = XmpPreset(
            id = id,
            name = name,
            category = category,
            isBuiltIn = true,
            exposure = exposure,
            contrast = contrast,
            highlights = highlights,
            shadows = shadows,
            whites = whites,
            blacks = blacks,
            temperature = temperature,
            tint = tint,
            vibrance = vibrance,
            saturation = saturation,
            clarity = clarity,
            dehaze = dehaze,
            vignette = vignette,
            grain = grain,
            shadowHue = shadowHue,
            shadowSat = shadowSat,
            highlightHue = highlightHue,
            highlightSat = highlightSat,
            balance = balance,
            toneCurvePoints = toneCurve
        )
        return preset.copy(rawXml = XmpParser.toXml(preset))
    }
